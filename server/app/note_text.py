"""AI 필기 다듬기: 학생 노트처럼 '내용'만 남긴다.

'시험에 꼭 나온다', '꼭 기억하세요', '중요!' 같은 말은 필기 종류(시험·강조 꼬리표)가 이미 보여 주므로 글에서 뺀다.
사람이 직접 쓴 필기는 건드리지 않는다 (AI 필기에만 쓴다).
"""

import re

_PARTICLE = r"(?:은|는|이|가|도)?"
_RULES: list[tuple[re.Pattern, str]] = [
    # "…은 중간고사 범위에 포함됩니다" → "…: 중간고사 범위"
    (re.compile(_PARTICLE + r"\s*(중간|기말)\s*고사\s*범위에\s*(?:포함|들어)\w*[.!~]*"), r": \1고사 범위"),
    # "…은 시험에 꼭 나온다 / 나와요 / 나옴 / 출제된다 / 나올 수 있음"
    (re.compile(r"\s*,?\s*(?:이것|이거|이건|여기)?\s*" + _PARTICLE + r"\s*(?:시험|중간고사|기말고사)에\s*(?:꼭|반드시|자주|잘|무조건|거의)?\s*"
                r"(?:나온다|나와요|나옵니다|나온대요|나옴|출제\w*|나올\s*(?:것|수)\s*\w*)[.!~]*"), ""),
    # "꼭 기억하세요 / 외워 두세요 / 암기할 것"
    (re.compile(r"\s*,?\s*(?:꼭|반드시|무조건)?\s*(?:기억|외워|암기)\s*(?:하세요|해\s*두세요|두세요|할\s*것|해야\s*함|하자|해\s*둘\s*것)[.!~]*"), ""),
    # "(교수님) 강조함 / 강조하심" · "중요!" · "매우 중요함" (앞뒤 장식 포함)
    (re.compile(r"\s*[-—–(]?\s*(?:교수님\s*)?강조(?:함|하심|했다|하셨다|하셨음)[)]?[.!]*"), ""),
    (re.compile(r"\s*[-—–(]?\s*(?:매우|정말|아주)?\s*중요(?:함|합니다|하다|해요)?\s*[!)]*\s*$"), ""),
    (re.compile(r"^\s*(?:⭐|★)?\s*(?:중요|시험|시험 포인트)\s*[:：]\s*"), ""),
]


def tidy(text: str) -> str:
    """AI 필기 글을 학생 노트처럼. 내용이 하나도 남지 않으면 '' (그 필기는 쓰지 않는다)"""
    out = text.strip()
    for pattern, repl in _RULES:
        out = pattern.sub(repl, out)
    out = re.sub(r"\s{2,}", " ", out).strip(" ,.·-—–:")
    out = re.sub(r"\(\s*\)", "", out).strip()
    # 남은 게 거의 없으면(예: "이거 시험에 꼭 나와요" 하나뿐) 필기로 쓰지 않는다
    return out if len(re.sub(r"[^\w가-힣]", "", out)) >= 4 else ""
